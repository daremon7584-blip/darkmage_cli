"""Packaging metadata checks for a clean `pip install .`."""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _project_dependencies() -> list[str]:
    text = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    try:
        import tomllib

        return list(tomllib.loads(text)["project"]["dependencies"])
    except (ImportError, KeyError):
        # Python 3.10 has no tomllib; the dependencies block is simple TOML.
        match = re.search(r"^dependencies\s*=\s*\[(.*?)\]", text, re.MULTILINE | re.DOTALL)
        assert match, "dependencies block not found"
        return re.findall(r'"([^"]+)"', match.group(1))


def _dependency_name(requirement: str) -> str:
    return re.split(r"[<>=!~\[ ;]", requirement, maxsplit=1)[0].lower().replace("_", "-")


def test_cryptography_is_declared():
    names = {_dependency_name(item) for item in _project_dependencies()}
    assert "cryptography" in names, f"missing cryptography in {sorted(names)}"


def test_security_module_imports_standalone():
    result = subprocess.run(
        [sys.executable, "-c", "import darkmage_cli.security"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stderr


def test_console_script_is_declared():
    text = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    assert 'darkmage = "darkmage_cli.cli:main"' in text


def test_version_has_a_single_source():
    import darkmage_cli

    text = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    assert 'dynamic = ["version"]' in text
    assert 'path = "darkmage_cli/__init__.py"' in text
    assert re.search(r'^__version__ = "[^"]+"', (ROOT / "darkmage_cli" / "__init__.py").read_text(encoding="utf-8"), re.MULTILINE)
    assert re.fullmatch(r"\d+\.\d+\.\d+(?:[.-][0-9A-Za-z.]+)?", darkmage_cli.__version__)


def test_textual_is_pinned_consistently():
    requirements = _project_dependencies()
    textual = [item for item in requirements if _dependency_name(item) == "textual"]
    assert textual == ["textual>=8,<9"], textual

    lock = (ROOT / "requirements.lock").read_text(encoding="utf-8")
    match = re.search(r"^textual==([0-9][^\s\\]*)", lock, re.MULTILINE)
    assert match, "textual is not pinned in requirements.lock"
    major = int(match.group(1).split(".")[0])
    assert major == 8, f"requirements.lock pins textual {match.group(1)}"


def test_lockfile_is_hashed_and_complete():
    lock = (ROOT / "requirements.lock").read_text(encoding="utf-8")
    assert "autogenerated by pip-compile" in lock
    for name in ("httpx", "websockets", "textual", "cryptography"):
        assert re.search(rf"^{name}==", lock, re.MULTILINE), name
    assert "--hash=sha256:" in lock


def test_ci_workflow_runs_the_cli_suite():
    workflow = (ROOT / ".github" / "workflows" / "cli.yml").read_text(encoding="utf-8")
    assert "python -m pytest -q" in workflow
    assert "requirements.lock" in workflow
    assert "--require-hashes" in workflow
    for version in ("3.10", "3.11", "3.12", "3.13"):
        assert f'"{version}"' in workflow
    assert "darkmage --version" in workflow


def test_module_version_runs_standalone():
    result = subprocess.run(
        [sys.executable, "-m", "darkmage_cli.cli", "--version"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stderr
    assert result.stdout.strip() == f"darkmage {__import__('darkmage_cli').__version__}"
